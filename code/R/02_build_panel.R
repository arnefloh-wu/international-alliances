# 02_build_panel.R
# Stage 6 (/panel-build), step 1 of 2: hire-level staffing frame and employee
# stocks, following the approved pre-analysis plan pap-v1.0
# (reviews/gate-5-pre-analysis-plan.md, A2.1, A2.2, A3, A4, B0.1 to B0.3).
#
# What it does
#   1. Reads the matched dataset v3 (core_main, 7,460 IJVs), the parents and
#      their Revelio families; the JV's own entity is never a parent employer.
#   2. Hires: a person's first dated position at the matched JV entity, for
#      people in the spell table; hire years from the formation year to 2025
#      (2010 to 2025 is the main period; earlier years stay for the full-period
#      robustness check). Occupation from the position-level O*NET code, else the
#      role lookup (onet_source); domain (SOC minor group, REG carved out),
#      domain_b (REG_B carved out, H4 grain), levels (mappings a and b), Revelio
#      function (role_k10) and role_k50.
#   3. Classifies every hire on the staffing frame of A2.2 for origin windows of
#      1, 3 (primary) and 5 years, and marks labor market entrants for education
#      windows of 1, 3 (primary) and 5 years.
#   4. Counts employees on 30 June per IJV x grain x year (cell rule), and staff
#      per IJV-year (coverage ratio).
#
# Independence and real_data_lock: no model is estimated, and nothing is
# tabulated by exposure, domain, level, score or year here. The frame's
# exposure_group column is dropped on read.
#
# Inputs (licensed, local only): see panel_config() in code/R/functions/panel_build.R.
# Outputs (gitignored, person level): <interim>/panel-hires-<tag>.parquet,
#   <interim>/panel-stock-<grain>-<tag>.parquet, <interim>/panel-staff-ijv-year-<tag>.parquet,
#   <interim>/panel-build-log-<tag>.csv (counts for the sample-construction log).
# Run from the repository root (real data: about 15 to 30 minutes):
#   "C:/Program Files/R/R-4.6.1/bin/Rscript.exe" code/R/02_build_panel.R            # real extracts
#   "C:/Program Files/R/R-4.6.1/bin/Rscript.exe" code/R/02_build_panel.R synthetic  # simulated twin
# A real-data rerun resumes at step 6 if the hire file and the log of steps 1 to 5
# exist; add the argument "rebuild" to start from scratch. Do not edit this file
# while it runs (Rscript reads it as it goes).

source("code/R/00_setup.R")
require_pkgs(c("arrow", "countrycode"))
source("code/R/functions/panel_build.R")
MODE <- if ("synthetic" %in% commandArgs(trailingOnly = TRUE)) "synthetic" else "real"
cfg <- panel_config(MODE)
dir.create(cfg$interim, showWarnings = FALSE, recursive = TRUE)
t0 <- Sys.time()
say <- function(...) message(format(Sys.time(), "%H:%M:%S"), " ", sprintf(...))
f_out <- function(name) file.path(cfg$interim, sprintf("panel-%s-%s.parquet", name, cfg$tag))
L <- new_log()

# ---- 1. IJVs, parents, families ---------------------------------------------------------
ijv <- fread(cfg$ijv, colClasses = list(character = "jv_bvdid"), na.strings = "")
if ("exposure_group" %in% names(ijv)) ijv[, exposure_group := NULL]
log_step(L, "1 IJVs", "matched frame (core_main of frame v3)", nrow(ijv), "IJVs", "ijv-matched table; one row per IJV")
stopifnot(!anyDuplicated(ijv$jv_bvdid), !anyDuplicated(ijv$rcid_jv))
par <- fread(cfg$parents, colClasses = list(character = c("jv_bvdid", "parent_bvdid", "parent_guo")), na.strings = "")
par[, host_direct := parent_country == ijv$jv_country[match(jv_bvdid, ijv$jv_bvdid)]]
grp <- fread(cfg$groups, colClasses = list(character = "parent_bvdid"))
fi <- build_families(ijv, par, grp)
log_step(L, "1 IJVs", "IJVs whose matched entity lies in a parent's Revelio family (flag_jv_in_parent_family; kept, audit of 2026-11-26)",
         length(fi$jv_in_family), "IJVs", "entity removed from the parent family for that IJV only")
log_step(L, "1 IJVs", "IJVs with an entity in two parents' families (flag_shared_family_entity)", length(fi$shared_ijv), "IJVs",
         "entity assigned to the parent with the larger equity share")
saveRDS(fi[c("jv_in_family", "shared_ijv", "n_shared_entities", "n_own_removed")], file.path(cfg$interim, sprintf("panel-families-%s.rds", cfg$tag)))

# ---- 2. Spells (employee stock) ----------------------------------------------------------
sp <- as.data.table(arrow::read_parquet(cfg$spells, col_select = c("jv_bvdid", "user_id", "position_id", "first_reference_year",
        "last_reference_year", "seniority", "role_k17000_v3", "function_role_k10", "role_k50_v3")))
log_step(L, "2 Spells", "positions in the spell table", nrow(sp), "positions")
n <- nrow(sp); sp <- unique(sp, by = "position_id")
log_step(L, "2 Spells", "after removing repeated position_id", nrow(sp), "positions", "copies after the first dropped", n - nrow(sp))
n <- nrow(sp); sp <- sp[jv_bvdid %chin% ijv$jv_bvdid]
log_step(L, "2 Spells", "filed under an IJV of the frame", nrow(sp), "positions", "stray entities dropped", n - nrow(sp))
n <- nrow(sp); sp <- sp[!is.na(first_reference_year) & !is.na(last_reference_year) & last_reference_year >= first_reference_year]
log_step(L, "2 Spells", "with valid 30 June reference years", nrow(sp), "positions", "positions without a reference year dropped", n - nrow(sp))
log_step(L, "2 Spells", "IJVs with at least one spell", uniqueN(sp$jv_bvdid), "IJVs")
log_step(L, "2 Spells", "people with spells at two or more IJVs (each person-IJV pair counted at its IJV)",
         unique(sp[, .(user_id, jv_bvdid)])[, .N, by = user_id][N > 1L, .N], "people")

# Occupation tables (used by the hires and by the stocks).
onet <- read_parts(cfg$onet_dir, c("position_id", "onet_code"))
n <- nrow(onet); onet <- unique(onet, by = "position_id")
stopifnot(n == nrow(onet))
lookup <- as.data.table(arrow::read_parquet(cfg$lookup, col_select = c("role_k17000_v3", "onet_code")))
occ <- fread(cfg$occ)

# Steps 3 to 5 are skipped on a real-data rerun when the hire file and the log of
# steps 1 to 5 exist (delete either to rebuild; argument "rebuild" forces it).
# Synthetic runs always rebuild.
f_log1 <- file.path(cfg$interim, sprintf("panel-build-log-part1-%s.csv", cfg$tag))
RESUME <- MODE == "real" && !"rebuild" %in% commandArgs(trailingOnly = TRUE) && file.exists(f_out("hires")) && file.exists(f_log1)
if (RESUME) {
  say("hires and the log of steps 1 to 5 found: resuming at step 6")
  prev <- fread(f_log1, colClasses = "character", na.strings = NULL)
  L$rows <- split(prev, seq_len(nrow(prev)))
} else {
# ---- 3. Hires ------------------------------------------------------------------------------
jp <- as.data.table(arrow::read_parquet(cfg$jvpos, col_select = c("user_id", "position_id", "rcid", "start_date", "seniority",
        "role_k17000_v3", "job_category", "role_k50_v3")))
n <- nrow(jp); jp <- unique(jp, by = "position_id")
log_step(L, "3 Hires", "positions at the matched JV entities (all, incl. stays without a 30 June)", nrow(jp), "positions",
         "repeated position_id dropped", n - nrow(jp))
jp[, start_date := as.IDate(start_date)]
hb <- build_hires(jp, sp, ijv)
rm(jp); invisible(gc())
log_step(L, "3 Hires", "person-IJV pairs in the spell table", hb$n_pairs, "pairs")
log_step(L, "3 Hires", "pairs without any position record at the JV entity", hb$n_no_position, "pairs", "dropped")
log_step(L, "3 Hires", "pairs with a dated first position (hires)", nrow(hb$hire), "hires",
         "pairs whose positions at the JV all lack a start date dropped", hb$n_undated)
H <- hb$hire[, .(jv_bvdid, user_id, rcid_jv = rcid, position_id, hire_date = start_date, hire_year = year(start_date),
                 seniority, role_k17000_v3, fn = pb_blank(job_category), role50 = pb_blank(role_k50_v3))]
rm(hb); invisible(gc())
H[fn %chin% "unknown", fn := NA_character_]
H[role50 %chin% "unknown", role50 := NA_character_]
H <- merge(H, ijv[, .(jv_bvdid, formation_year, host = jv_country)], by = "jv_bvdid")
n <- nrow(H); H <- H[hire_year >= formation_year]
log_step(L, "3 Hires", "hire year from the formation year on", nrow(H), "hires", "hired before the formation (incorporation) year", n - nrow(H))
n <- nrow(H); H <- H[hire_year <= PANEL_END]
log_step(L, "3 Hires", sprintf("hire year up to %d", PANEL_END), nrow(H), "hires", "hired in 2026 (Revelio data end 2026-09)", n - nrow(H))
log_step(L, "3 Hires", sprintf("of these, hire year %d to %d (main period)", MAIN_START, PANEL_END), H[hire_year >= MAIN_START, .N], "hires",
         "earlier hires kept for the full-period check (main_period = 0)")
H[, hire_in_spells := position_id %in% sp$position_id]
log_step(L, "3 Hires", "hires whose first position covers no 30 June (not in the spell table; occupation from the role lookup)",
         H[hire_in_spells == FALSE, .N], "hires")
log_step(L, "3 Hires", "people hired by two or more IJVs (a hire at each)", H[, .N, by = user_id][N > 1L, .N], "people")

# Occupation, domains, levels.
attach_onet(H, onet, lookup); attach_occupation(H, occ)
H[, `:=`(level = level_of(seniority, "a"), level_b = level_of(seniority, "b"))]
log_step(L, "3 Hires", "hires coded through the role lookup (onet_source = lookup)", H[onet_source == "lookup", .N], "hires")
log_step(L, "3 Hires", "hires without a usable O*NET code (unknown, Retired, On Leave, missing): no domain", H[is.na(onet_code), .N], "hires")
log_step(L, "3 Hires", "hires in occupations with imputed scores (score_imputed)", H[score_imputed_occ %in% TRUE, .N], "hires")
log_step(L, "3 Hires", "hires without a Revelio seniority: no level", H[is.na(level), .N], "hires")

# ---- 4. Career histories and the staffing frame -----------------------------------------------
hist <- read_parts(cfg$hist_dir, c("user_id", "position_id", "rcid", "start_date", "end_date", "country"))
log_step(L, "4 Histories", "history positions read", nrow(hist), "positions")
n <- nrow(hist); hist <- unique(hist, by = "position_id")
log_step(L, "4 Histories", "after removing repeated position_id", nrow(hist), "positions", "copies after the first dropped", n - nrow(hist))
hist <- hist[user_id %in% H$user_id]
log_step(L, "4 Histories", "positions of hired people", nrow(hist), "positions")
log_step(L, "4 Histories", "hired people without any history position", sum(!unique(H$user_id) %in% hist$user_id), "people")
hist[, `:=`(start_date = as.IDate(start_date), end_date = as.IDate(end_date))]
n <- nrow(hist); hist <- hist[!is.na(start_date)]
log_step(L, "4 Histories", "with a start date", nrow(hist), "positions", "positions without a start date cannot precede a hire; dropped", n - nrow(hist))
n <- nrow(hist); hist <- hist[is.na(end_date) | end_date >= start_date]
log_step(L, "4 Histories", "end date not before start date", nrow(hist), "positions", "positions ending before they start dropped", n - nrow(hist))
log_step(L, "4 Histories", "open-ended positions (no end date; treated as held until today)", hist[is.na(end_date), .N], "positions")
log_step(L, "4 Histories", "positions at employers not mapped to a Revelio company (count as independent)", hist[is.na(rcid), .N], "positions")
hist[, p_iso := to_iso2(country)]
log_step(L, "4 Histories", "positions without a country that converts to ISO 2", hist[is.na(p_iso), .N], "positions")
hist[, country := NULL]
say("classifying %d hires", nrow(H))
cl <- classify_hires(H, hist, fi$fam, K = cfg$K)
rm(hist); invisible(gc())
H <- merge(H, cl, by = c("user_id", "jv_bvdid"), all.x = TRUE)
stopifnot(!anyNA(H$cat_w3), !anyNA(H$cat_w1), !anyNA(H$cat_w5))
# International parent-origin hires whose prior position was in the home country of a
# foreign direct parent (n_intl_parent_home, C1 parts b and c).
fp <- unique(par[host_direct %in% FALSE, .(jv_bvdid, p_iso = parent_country)])
H[, home_country := cat_w3 == "intl_parent" & paste(jv_bvdid, p_iso) %chin% fp[, paste(jv_bvdid, p_iso)]]

# ---- 5. Education: labor market entrants -------------------------------------------------------
edu <- read_parts(cfg$edu_dir, c("user_id", "education_number", "enddate", "university_country"))
edu[, enddate := as.IDate(enddate)]
add_entrants(H, edu)
rm(edu); invisible(gc())
stopifnot(all(!H$entrant_e3 | H$cat_w3 == "not_obs"), all(!H$entrant_e5 | H$cat_w1 == "not_obs"))
H[, year := hire_year]
arrow::write_parquet(H[, .(jv_bvdid, user_id, year, hire_date, position_id, hire_in_spells, onet_code, onet_source, score_imputed_occ,
                           domain, domain_b, seniority, level, level_b, fn, role50, has_earlier, cat_w1, cat_w3, cat_w5,
                           p_host, p_iso, employer_mapped, home_country, entrant_e1, entrant_e3, entrant_e5, entrant_place, host)],
                     f_out("hires"))
log_step(L, "5 Frame", "hires classified (all years from formation to 2025)", nrow(H), "hires")
rm(H); invisible(gc())
fwrite(log_table(L), f_log1)
}

# ---- 6. Employee stocks per grain (cell rule) and staff per IJV-year ---------------------------
attach_onet(sp, onet, lookup); attach_occupation(sp, occ)
rm(onet, lookup); invisible(gc())
sp <- merge(sp, ijv[, .(jv_bvdid, formation_year)], by = "jv_bvdid")
sp[, `:=`(level = level_of(seniority, "a"), level_b = level_of(seniority, "b"), fn = pb_blank(function_role_k10),
          role50 = pb_blank(role_k50_v3), keep_xi = score_imputed_occ %in% FALSE, keep_xl = onet_source == "position")]
sp[fn %chin% "unknown", fn := NA_character_]; sp[role50 %chin% "unknown", role50 := NA_character_]
sp[, seniority := as.integer(seniority)]
years <- seq(max(min(sp$first_reference_year, na.rm = TRUE), 1950L), PANEL_END)
log_step(L, "6 Stock", "spells without a usable O*NET code (not in the domain stocks)", sp[is.na(onet_code), .N], "positions")
log_step(L, "6 Stock", "spells without a seniority (not in the level stocks)", sp[is.na(level), .N], "positions")
GRAINS <- c("domain", "domain_b", "level", "level_b", "seniority", "fn", "role50")
say("stocks: %s", paste(GRAINS, collapse = ", "))
stocks <- stock_counts_all(sp, GRAINS, years, restrict = list(domain = c("keep_xi", "keep_xl"), domain_b = c("keep_xi", "keep_xl")))
for (g in GRAINS) {
  arrow::write_parquet(stocks[[g]], f_out(paste0("stock-", g)))
  log_step(L, "6 Stock", sprintf("IJV x %s x year cells with at least one employee on 30 June", g), nrow(stocks[[g]]), "cells")
}
rm(stocks); invisible(gc())
staff <- rbindlist(lapply(years, function(y)
  sp[first_reference_year <= y & last_reference_year >= y & formation_year <= y, .(staff_revelio = uniqueN(user_id)), by = jv_bvdid][, year := y]))
arrow::write_parquet(staff, f_out("staff-ijv-year"))
fwrite(log_table(L), file.path(cfg$interim, sprintf("panel-build-log-%s.csv", cfg$tag)))
say("02_build_panel.R done (%s) in %.1f minutes", MODE, as.numeric(difftime(Sys.time(), t0, units = "mins")))
